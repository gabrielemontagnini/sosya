"""Render a `range.yaml` into an isolated `docker-compose.yml`. Pure and deterministic.

The rules come from docs/architecture.md: one internal, gateway-isolated, IPv4-only network
per segment; no published ports; the attacker box is the only container with internet access
and never forwards packets. Vulhub definitions are copied key by key through the allowlist in
`sosya.catalog.rules`: anything else makes rendering fail with the environment id.
"""

import copy
import posixpath
from collections.abc import Callable, Mapping
from pathlib import Path
from typing import Any

import yaml

from sosya import topology
from sosya.catalog.models import CatalogIndex, Entry, Service
from sosya.catalog.rules import (
    HOST_LEVEL_KEYS,
    REWRITTEN_KEYS,
    SAFE_KEYS,
    interpolate,
    parse_volume,
)
from sosya.spec import Host, RangeSpec, check_catalog, errors

PROJECT_PREFIX = "sosya-"
LABEL_RANGE = "sosya.range"
LABEL_HOST = "sosya.host"
LABEL_ROLE = "sosya.role"
DEFAULT_PLATFORM = "linux/amd64"
PIDS_LIMIT = 1024
LOGGING = {"driver": "json-file", "options": {"max-size": "10m", "max-file": "3"}}
SEGMENT_NETWORK: dict[str, Any] = {
    "internal": True,
    "enable_ipv6": False,
    "driver_opts": {"com.docker.network.bridge.gateway_mode_ipv4": "isolated"},
}
# A restart policy that would bring a vulnerable target back after a daemon or host restart.
_PERSISTENT_RESTART = {"always": "on-failure", "unless-stopped": "on-failure"}
_RESERVED_LABELS = ("sosya.", "com.docker.")
HEADER = "# Generated by sosya from range.yaml. Do not edit: run `sosya up` again instead.\n"


class RenderError(ValueError):
    pass


def project_name(range_name: str) -> str:
    return f"{PROJECT_PREFIX}{range_name}"


def _put(mapping: dict[str, Any], key: str, value: Any, what: str) -> None:
    if key in mapping:
        raise RenderError(f"{what} {key!r} would be generated twice")
    mapping[key] = value


def choose_platform(service: Service, engine_platform: str | None) -> str | None:
    """The engine's platform when the image has it, else amd64 (emulated), else unknown."""
    platforms = service.platforms or []
    if engine_platform in platforms:
        return engine_platform
    if DEFAULT_PLATFORM in platforms:
        return DEFAULT_PLATFORM
    return platforms[0] if platforms else None


def _inside(root: Path, relative: str, entry_id: str) -> str:
    normalized = posixpath.normpath(relative)
    if normalized == ".." or normalized.startswith(("../", "/")):
        raise RenderError(f"{entry_id}: path {relative!r} leaves the component directory")
    return str(root) if normalized == "." else str(root / normalized)


class _Context:
    def __init__(
        self,
        spec: RangeSpec,
        entry: Entry,
        host: Host,
        keys: dict[str, str],
        source_dir: Path | None,
        files_dir: Path | None,
    ) -> None:
        self.spec = spec
        self.entry = entry
        self.host = host
        self.keys = keys
        self.source_dir = source_dir
        self.files_dir = files_dir

    def source(self, relative: str) -> str:
        if self.source_dir is None:
            raise RenderError(f"{self.entry.id}: needs its Vulhub files, which are not available")
        return _inside(self.source_dir, relative, self.entry.id)

    def copy(self, relative: str) -> str:
        if self.files_dir is None:
            raise RenderError(f"{self.entry.id}: needs a copy of its files, which is not available")
        return _inside(self.files_dir, relative, self.entry.id)

    def rename(self, name: str) -> str:
        if name not in self.keys:
            raise RenderError(f"{self.entry.id}: depends on unknown service {name!r}")
        return self.keys[name]


def _depends_on(value: Any, ctx: _Context) -> Any:
    if isinstance(value, Mapping):
        return {ctx.rename(name): copy.deepcopy(condition) for name, condition in value.items()}
    return [ctx.rename(name) for name in value]


def _build(value: Any, ctx: _Context) -> dict[str, Any]:
    build = {"context": value} if isinstance(value, str) else dict(value)
    unknown = set(build) - {"context", "dockerfile"}
    if unknown:
        raise RenderError(f"{ctx.entry.id}: build key(s) {sorted(unknown)} are not supported")
    build["context"] = ctx.source(str(build.get("context", ".")))
    return build


def _env_file(value: Any, ctx: _Context) -> list[Any]:
    items = [value] if isinstance(value, str | Mapping) else list(value)
    result: list[Any] = []
    for item in items:
        if isinstance(item, Mapping):
            result.append({**item, "path": ctx.source(str(item["path"]))})
        else:
            result.append(ctx.source(str(item)))
    return result


def _volumes(value: Any, ctx: _Context) -> list[str]:
    result = []
    for item in value:
        volume = parse_volume(item)
        if volume is None or (volume.source is not None and not volume.is_bind):
            raise RenderError(f"{ctx.entry.id}: volume {item!r} is not supported")
        if volume.source is None:
            result.append(str(item))
            continue
        rest = str(item).split(":", 1)[1]
        if volume.source.startswith(("/", "~")):
            result.append(str(item))  # dangerous host bind, allowed only with consent
        else:
            result.append(f"{ctx.copy(volume.source)}:{rest}")
    return result


def _labels(value: Any, ctx: _Context) -> dict[str, str]:
    if isinstance(value, Mapping):
        labels = {str(k): str(v) for k, v in value.items()}
    else:
        labels = dict(str(item).partition("=")[::2] for item in value)
    for key in labels:
        if key.startswith(_RESERVED_LABELS):
            raise RenderError(f"{ctx.entry.id}: label {key!r} is reserved")
    return labels


def _target_labels(ctx: _Context) -> dict[str, str]:
    return {LABEL_RANGE: ctx.spec.name, LABEL_HOST: ctx.host.name, LABEL_ROLE: "target"}


def _service(
    name: str,
    definition: Mapping[str, Any],
    container: topology.Container,
    service: Service,
    ctx: _Context,
    engine_platform: str | None,
) -> dict[str, Any]:
    definition = interpolate(definition)
    out: dict[str, Any] = {}
    labels: dict[str, str] = {}
    for key, value in definition.items():
        if key in REWRITTEN_KEYS:
            continue  # ports, container_name, links and networks: handled by the topology
        if key in HOST_LEVEL_KEYS:
            if key == "network_mode" and container.shares_network_of is not None:
                out[key] = f"service:{container.shares_network_of}"
            elif ctx.entry.is_dangerous:
                out[key] = copy.deepcopy(value)  # check_catalog required consent
            else:
                raise RenderError(f"{ctx.entry.id}: service {name}: {key} needs consent")
            continue
        if key not in SAFE_KEYS:
            raise RenderError(f"{ctx.entry.id}: service {name}: key {key!r} is not supported")
        if key == "depends_on":
            out[key] = _depends_on(value, ctx)
        elif key == "build":
            out[key] = _build(value, ctx)
        elif key == "env_file":
            out[key] = _env_file(value, ctx)
        elif key == "volumes":
            out[key] = _volumes(value, ctx)
        elif key == "labels":
            labels = _labels(value, ctx)
        elif key == "restart":
            out[key] = _PERSISTENT_RESTART.get(str(value), value)
        else:
            out[key] = copy.deepcopy(value)
    platform = choose_platform(service, engine_platform)
    if platform is not None:
        out["platform"] = platform
    if container.shares_network_of is None:
        networks: dict[str, Any] = {segment: {} for segment in container.segments}
        if container.private is not None:
            networks[container.private] = {"aliases": list(container.private_aliases)}
        out["networks"] = networks
    out["labels"] = {**labels, **_target_labels(ctx)}
    out["pids_limit"] = PIDS_LIMIT
    out["logging"] = copy.deepcopy(LOGGING)
    return out


def _attacker(spec: RangeSpec, container: topology.Container, image: str) -> dict[str, Any]:
    return {
        "image": image,
        "hostname": topology.ATTACKER,
        "init": True,
        # Defense in depth: the attacker box never routes packets between networks.
        "sysctls": {"net.ipv4.ip_forward": "0"},
        "networks": {network: {} for network in container.segments},
        "labels": {LABEL_RANGE: spec.name, LABEL_HOST: topology.ATTACKER, LABEL_ROLE: "attacker"},
        "logging": copy.deepcopy(LOGGING),
    }


def render(
    spec: RangeSpec,
    index: CatalogIndex,
    *,
    services_of: Callable[[str], Mapping[str, Mapping[str, Any]]],
    attacker_image: str,
    engine_platform: str | None,
    allow_privileged: bool = False,
    source_dir: Callable[[Entry], Path] | None = None,
    files_dir: Path | None = None,
) -> dict[str, Any]:
    """Return the compose project as a mapping. Raise `RenderError` on anything not allowed.

    `source_dir(entry)` is the shared, read-only Vulhub checkout of a component, used for
    `build` and `env_file`. `files_dir / <host>` is the range's own copy of the component's
    files, used for bind mounts, because targets are compromised by design.
    """
    problems = errors(
        check_catalog(
            spec,
            index,
            host_platform=engine_platform,
            allow_privileged=allow_privileged,
            services_of=services_of,
        )
    )
    if problems:
        raise RenderError("; ".join(str(problem) for problem in problems))
    plan = topology.build(spec, services_of)
    services: dict[str, Any] = {}
    for host in spec.hosts:
        entry = index.get(host.component)
        assert entry is not None  # check_catalog
        definitions = services_of(entry.id)
        by_name = {service.name: service for service in entry.services}
        ctx = _Context(
            spec,
            entry,
            host,
            plan.key_map(host.name),
            source_dir(entry) if source_dir and not entry.image_only else None,
            files_dir / host.name if files_dir else None,
        )
        for container in plan.of_host(host.name):
            definition = definitions[container.original]
            if container.original not in by_name:
                raise RenderError(f"{entry.id}: service {container.original} is not in the index")
            rendered = _service(
                container.original,
                definition,
                container,
                by_name[container.original],
                ctx,
                engine_platform,
            )
            _put(services, container.key, rendered, "service")
    attacker = next(c for c in plan.containers if c.host == topology.ATTACKER)
    _put(services, attacker.key, _attacker(spec, attacker, attacker_image), "service")

    network_labels = {LABEL_RANGE: spec.name}
    networks: dict[str, Any] = {}
    for name in (*plan.segments, *plan.private_networks):
        _put(
            networks, name, {**copy.deepcopy(SEGMENT_NETWORK), "labels": network_labels}, "network"
        )
    if plan.egress:
        # A plain bridge with internet access. Only the attacker box joins it.
        _put(networks, topology.EGRESS, {"labels": network_labels}, "network")
    return {"name": project_name(spec.name), "services": services, "networks": networks}


class _Dumper(yaml.SafeDumper):
    """Never write YAML anchors: the file must read the same as what Compose sees."""

    def ignore_aliases(self, data: Any) -> bool:
        return True


def dump(compose: Mapping[str, Any]) -> str:
    body = yaml.dump(dict(compose), Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=1000)
    return HEADER + body
